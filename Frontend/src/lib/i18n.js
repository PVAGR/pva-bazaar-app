Object.entries(EXTRA_TRANSLATIONS).forEach(([lang, pack]) => {
  STRINGS[lang] = { ...fallback, ...pack };
});

export const getDefaultLanguage = () => {
  const preferred = import.meta.env.VITE_DEFAULT_LANG || 'en';
  return LANGUAGE_OPTIONS.some((item) => item.code === preferred) ? preferred : 'en';
};

export const getStoredLanguage = () => {
  const current = globalThis.localStorage?.getItem(LANGUAGE_KEY);
  if (current && LANGUAGE_OPTIONS.some((item) => item.code === current)) return current;
  return getDefaultLanguage();
};

export const setStoredLanguage = (lang) => {
  const next = LANGUAGE_OPTIONS.some((item) => item.code === lang) ? lang : 'en';
  globalThis.localStorage?.setItem(LANGUAGE_KEY, next);
  globalThis.document?.documentElement?.setAttribute('lang', next);
  globalThis.window?.dispatchEvent(new globalThis.CustomEvent('pva-language-change', { detail: next }));
  return next;
};

export const translate = (lang, key) => {
  const pack = STRINGS[lang] || fallback;
  return pack[key] || fallback[key] || key;
};

export const bindLanguageSync = (setLang) => {
  const handleLanguageChange = (event) => {
    setLang(event?.detail || getStoredLanguage());
  };

  globalThis.window?.addEventListener('pva-language-change', handleLanguageChange);
  return () => globalThis.window?.removeEventListener('pva-language-change', handleLanguageChange);
};
