/**
 * Get AI insights about seller performance
 * GET /api/ai-help/performance-insights
 */
router.get('/performance-insights', authenticateToken, async (req, res) => {
  try {
    const userId = req.user.id;

    // Get latest analytics
    const analytics = await SellerAnalytics.findOne({ sellerId: userId }).sort({ createdAt: -1 });

    if (!analytics) {
      return res.json({
        insights: ['Start by creating your first product to get performance insights'],
      });
    }

    const insights = [];

    // Conversion rate analysis
    if (analytics.conversionRate && analytics.conversionRate < 2) {
      insights.push({
        category: 'Conversion',
        priority: 'high',
        insight: `Your conversion rate is ${analytics.conversionRate}%, below market average 2-3%. Try: better product photos, detailed descriptions, customer testimonials.`,
      });
    }

    // Traffic analysis
    if (analytics.pageViews > 0 && analytics.checkoutStarts / analytics.pageViews < 0.1) {
      insights.push({
        category: 'Traffic',
        priority: 'medium',
        insight: `Only ${(analytics.checkoutStarts / analytics.pageViews * 100).toFixed(1)}% of visitors view checkout. Improve: product descriptions, add reviews, reduce checkout friction.`,
      });
    }

    // Revenue growth
    if (analytics.totalRevenue === 0) {
      insights.push({
        category: 'Revenue',
        priority: 'high',
        insight: `No sales yet. Focus on: creating quality product listings, using relevant tags, and responding quickly to customer inquiries.`,
      });
    }

    // Pricing insights
    insights.push({
      category: 'Pricing',
      priority: 'medium',
      insight: `Use our Fair Price Calculator to ensure competitive pricing. Current avg order value: $${analytics.avgOrderValue || 0}`,
    });

    // Recommendations
    const recommendations = [
      'Add at least 10 high-quality product photos',
      'Write detailed product descriptions (200+ characters)',
      'Respond to inquiries within 1 hour',
      'Offer competitive shipping rates',
      'Ask satisfied customers for reviews',
    ];

    res.json({
      insights,
      recommendations,
      nextSteps: insights.filter((i) => i.priority === 'high').map((i) => i.insight),
    });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

/**
 * Rate AI assistance helpfulness
 * POST /api/ai-help/rate-session
 */
router.post('/rate-session', authenticateToken, async (req, res) => {
  try {
    const { sessionId, rating, comment } = req.body;

    if (!sessionId || !rating) {
      return res.status(400).json({ error: 'sessionId and rating required' });
    }

    if (rating < 1 || rating > 5) {
      return res.status(400).json({ error: 'rating must be 1-5' });
    }

    const session = await AIAgentBot.findByIdAndUpdate(
      sessionId,
      {
        resolved: true,
        resolvedAt: new Date(),
        satisfactionRating: rating,
        satisfactionComment: comment,
      },
      { new: true }
    );

    res.json({ success: true, session });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

