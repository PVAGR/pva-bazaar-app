/**
 * Ask AI assistant a question
 * POST /api/ai-help/ask
 */
router.post('/ask', authenticateToken, async (req, res) => {
  try {
    const { question, topic = 'general', sessionId } = req.body;
    const userId = req.user.id;

    if (!question) {
      return res.status(400).json({ error: 'question required' });
    }

    // Find or create session
    let session = sessionId ? await AIAgentBot.findById(sessionId) : null;

    if (!session) {
      session = new AIAgentBot({
        userId,
        topic,
        sessionId: `${userId}-${Date.now()}`,
      });
    }

    // Add user message
    session.conversation.push({
      role: 'user',
      message: question,
    });

    // Generate AI response
    const aiResponse = await generateAIResponse(session.conversation, topic);

    session.conversation.push({
      role: 'assistant',
      message: aiResponse.message,
    });

    await session.save();

    res.json({
      sessionId: session._id,
      response: aiResponse.message,
      suggestions: aiResponse.suggestions,
    });
  } catch (error) {
    res.status(500).json({ error: error.message });
  }
});

