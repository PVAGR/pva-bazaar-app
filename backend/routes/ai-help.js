/**
 * Get AI pricing suggestions
 * POST /api/ai-help/pricing-suggest
 */
router.post('/pricing-suggest', authenticateToken, async (req, res) => {
  try {
    const { productId, cost, targetMargin, condition, category } = req.body;
    const userId = req.user.id;

    if (!productId || !cost || !targetMargin) {
      return res.status(400).json({ error: 'productId, cost, targetMargin required' });
    }

    // Get fair price recommendation from pricing service
    const fairPrice = await pricingService.calculateFairPrice(productId, { condition, category });

    // Calculate target price with margin
    const targetPrice = Math.round(cost / (1 - targetMargin / 100));

    // Create recommendation
    const recommendation = {
      fairPrice: fairPrice.price,
      fairPriceRationale: `Market average: $${fairPrice.marketAvg}, range: $${fairPrice.minPrice} - $${fairPrice.maxPrice}`,
      recommendedPrice: Math.round((fairPrice.price + targetPrice) / 2), // Blend fair price with target
      targetPrice,
      urgencyOptions: {
        standard: fairPrice.price,
        promotional: Math.round(fairPrice.price * 0.85),
        premium: Math.round(fairPrice.price * 1.2),
        clearance: Math.round(fairPrice.price * 0.7),
      },
      estimatedSalesVelocity: {
        atFairPrice: '15-25 units/month (estimate)',
        atPromotionalPrice: '30-40 units/month',
        atPremiumPrice: '5-10 units/month',
      },
    };

    res.json(recommendation);
  } catch (error) {
    res.status(400).json({ error: error.message });
  }
});

